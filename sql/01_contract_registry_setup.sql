    APPROVAL_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CONTRACT_ID VARCHAR(128) NOT NULL,
    FROM_VERSION VARCHAR(20) NOT NULL,
    TO_VERSION VARCHAR(20) NOT NULL,
