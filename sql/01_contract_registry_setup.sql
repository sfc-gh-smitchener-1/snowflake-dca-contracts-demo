-- Register a new contract from YAML
CREATE OR REPLACE PROCEDURE GOVERNANCE.CONTRACT_REGISTRY.REGISTER_CONTRACT(
    P_CONTRACT_YAML TEXT
)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    v_contract_id VARCHAR;
    v_version VARCHAR;
    v_contract_type VARCHAR;
    v_yaml VARIANT;
BEGIN
    -- Parse YAML (stored as VARIANT)
    v_yaml := PARSE_JSON(P_CONTRACT_YAML);
    
    -- Determine contract type and extract ID/version
    IF (v_yaml:contract IS NOT NULL) THEN
        v_contract_type := 'data';
        v_contract_id := v_yaml:contract:id::VARCHAR;
        v_version := v_yaml:contract:version::VARCHAR;
    ELSIF (v_yaml:product IS NOT NULL) THEN
        v_contract_type := 'product';
        v_contract_id := v_yaml:product:id::VARCHAR;
        v_version := v_yaml:product:version::VARCHAR;
    ELSE
        RETURN 'ERROR: Invalid contract format - missing contract or product key';
    END IF;
    
    -- Insert or update contract
    MERGE INTO GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS tgt
    USING (SELECT :v_contract_id AS cid, :v_version AS ver) src
    ON tgt.CONTRACT_ID = src.cid AND tgt.VERSION = src.ver
    WHEN MATCHED THEN
        UPDATE SET 
            YAML_DEFINITION = :v_yaml,
            UPDATED_AT = CURRENT_TIMESTAMP(),
            UPDATED_BY = CURRENT_USER()
    WHEN NOT MATCHED THEN
        INSERT (CONTRACT_ID, CONTRACT_TYPE, VERSION, STATUS, YAML_DEFINITION)
        VALUES (:v_contract_id, :v_contract_type, :v_version, 'draft', :v_yaml);
    
    RETURN 'Contract registered: ' || v_contract_id || ' v' || v_version;
END;
$$;

-- Notify consumers of breaking change
CREATE OR REPLACE PROCEDURE GOVERNANCE.CONTRACT_REGISTRY.NOTIFY_BREAKING_CHANGE(
    P_CONTRACT_ID VARCHAR,
    P_FROM_VERSION VARCHAR,
    P_TO_VERSION VARCHAR,
    P_DEADLINE_DAYS INT DEFAULT 14
)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    v_consumer_count INT DEFAULT 0;
    c1 CURSOR FOR 
        SELECT COUNT(*) AS cnt
        FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS
        WHERE CONTRACT_ID = ?
          AND NOTIFY_BREAKING = TRUE;
BEGIN
    -- Get count of consumers to notify
    OPEN c1 USING (P_CONTRACT_ID);
    FETCH c1 INTO v_consumer_count;
    CLOSE c1;
    
    -- Insert approval requests for all consumers who want breaking change notifications
    INSERT INTO GOVERNANCE.CONTRACT_REGISTRY.BREAKING_CHANGE_APPROVALS
        (APPROVAL_ID, CONTRACT_ID, FROM_VERSION, TO_VERSION, CONSUMER_ID, STATUS, DEADLINE_AT)
    SELECT 
        UUID_STRING(),
        P_CONTRACT_ID,
        P_FROM_VERSION,
        P_TO_VERSION,
        CONSUMER_ID,
        'pending',
        DATEADD('day', P_DEADLINE_DAYS, CURRENT_TIMESTAMP())
    FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS
    WHERE CONTRACT_ID = P_CONTRACT_ID
      AND NOTIFY_BREAKING = TRUE;
    
    RETURN 'Created ' || v_consumer_count::VARCHAR || ' approval requests for contract ' || P_CONTRACT_ID;
END;
$$;

