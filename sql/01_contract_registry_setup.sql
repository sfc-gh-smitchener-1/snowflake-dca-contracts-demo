-- ─────────────────────────────────────────────────────────────────────────────
-- DATABASE & SCHEMA SETUP
-- ─────────────────────────────────────────────────────────────────────────────

USE ROLE ACCOUNTADMIN;

-- Create governance database if not exists
CREATE DATABASE IF NOT EXISTS GOVERNANCE;

-- Set database context
USE DATABASE GOVERNANCE;

-- Create contract registry schema
CREATE SCHEMA IF NOT EXISTS CONTRACT_REGISTRY;

-- Create observability schema for monitoring views
CREATE SCHEMA IF NOT EXISTS OBSERVABILITY;

-- Set schema context
USE SCHEMA CONTRACT_REGISTRY;

-- ─────────────────────────────────────────────────────────────────────────────
-- CONTRACT REGISTRY TABLES
-- ─────────────────────────────────────────────────────────────────────────────

-- Core contracts table
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS (
    CONTRACT_ID VARCHAR(128) NOT NULL,
    CONTRACT_TYPE VARCHAR(20) NOT NULL,  -- 'data' or 'product'
    VERSION VARCHAR(20) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'draft',
    PRODUCER_SYSTEM VARCHAR(256),
    PRODUCER_TEAM VARCHAR(256),
    PRODUCER_EMAIL VARCHAR(256),
    DESCRIPTION TEXT,
    YAML_DEFINITION VARIANT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
    UPDATED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
    PRIMARY KEY (CONTRACT_ID, VERSION)
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS IS 
'Central registry of all data and product contracts';

-- Contract version history
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_VERSIONS (
    VERSION_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CONTRACT_ID VARCHAR(128) NOT NULL,
    VERSION VARCHAR(20) NOT NULL,
    PREVIOUS_VERSION VARCHAR(20),
    CHANGE_TYPE VARCHAR(20) NOT NULL,  -- 'major', 'minor', 'patch'
    CHANGE_DESCRIPTION TEXT,
    BREAKING_CHANGES ARRAY,
    YAML_DEFINITION VARIANT,
    STATUS VARCHAR(20) DEFAULT 'pending',  -- 'pending', 'approved', 'deployed', 'rolled_back'
    DEPLOYED_AT TIMESTAMP_NTZ,
    DEPLOYED_BY VARCHAR(256),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY VARCHAR(256) DEFAULT CURRENT_USER()
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_VERSIONS IS 
'Version history for all contracts with change tracking';

-- Contract column definitions
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_COLUMNS (
    COLUMN_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CONTRACT_ID VARCHAR(128) NOT NULL,
    VERSION VARCHAR(20) NOT NULL,
    COLUMN_NAME VARCHAR(256) NOT NULL,
    DATA_TYPE VARCHAR(128),
    DESCRIPTION TEXT,
    IS_NULLABLE BOOLEAN DEFAULT TRUE,
    IS_PRIMARY_KEY BOOLEAN DEFAULT FALSE,
    IS_SYSTEM_MANAGED BOOLEAN DEFAULT FALSE,
    CONSTRAINTS ARRAY,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_COLUMNS IS 
'Column-level definitions for each contract version';

-- Column tags
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.COLUMN_TAGS (
    TAG_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    COLUMN_ID VARCHAR(64) NOT NULL,
    TAG_NAME VARCHAR(128) NOT NULL,
    TAG_VALUE VARCHAR(256) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.COLUMN_TAGS IS 
'Governance tags applied to contract columns';

-- Consumer registrations
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS (
    CONSUMER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CONTRACT_ID VARCHAR(128) NOT NULL,
    CONSUMER_TEAM VARCHAR(256) NOT NULL,
    CONSUMER_EMAIL VARCHAR(256) NOT NULL,
    SLACK_CHANNEL VARCHAR(128),
    USE_CASE TEXT,
    ACCESS_LEVEL VARCHAR(50),
    REQUIRED_COLUMNS ARRAY,
    NOTIFY_BREAKING BOOLEAN DEFAULT TRUE,
    NOTIFY_DEPRECATION BOOLEAN DEFAULT TRUE,
    NOTIFY_MINOR BOOLEAN DEFAULT FALSE,
    ACKNOWLEDGED_VERSION VARCHAR(20),
    REGISTERED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REGISTERED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
    LAST_ACKNOWLEDGED_AT TIMESTAMP_NTZ
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS IS 
'Registry of teams consuming each contract';

-- SLA definitions
CREATE TABLE IF NOT EXISTS GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_SLAS (
    SLA_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CONTRACT_ID VARCHAR(128) NOT NULL,
    VERSION VARCHAR(20) NOT NULL,
    SLA_TYPE VARCHAR(50) NOT NULL,  -- 'freshness', 'completeness', 'availability', 'volume'
    METRIC_NAME VARCHAR(128),
    THRESHOLD_VALUE FLOAT,
    THRESHOLD_UNIT VARCHAR(32),
    MEASUREMENT_SQL TEXT,
    SEVERITY VARCHAR(20) DEFAULT 'warning',
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_SLAS IS 
'SLA definitions for each contract';

-- Quality rules
