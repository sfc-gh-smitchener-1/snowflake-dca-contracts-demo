-- Active contracts view
CREATE OR REPLACE VIEW GOVERNANCE.CONTRACT_REGISTRY.VW_ACTIVE_CONTRACTS AS
SELECT 
    c.CONTRACT_ID,
    c.CONTRACT_TYPE,
    c.VERSION,
    c.PRODUCER_SYSTEM,
    c.PRODUCER_TEAM,
    c.PRODUCER_EMAIL,
    c.DESCRIPTION,
    c.CREATED_AT,
    c.UPDATED_AT,
    COUNT(DISTINCT con.CONSUMER_ID) AS CONSUMER_COUNT,
    COUNT(DISTINCT col.COLUMN_ID) AS COLUMN_COUNT
FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS c
LEFT JOIN GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS con 
    ON c.CONTRACT_ID = con.CONTRACT_ID
LEFT JOIN GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_COLUMNS col 
    ON c.CONTRACT_ID = col.CONTRACT_ID AND c.VERSION = col.VERSION
WHERE c.STATUS = 'active'
GROUP BY 
    c.CONTRACT_ID, c.CONTRACT_TYPE, c.VERSION, c.PRODUCER_SYSTEM,
    c.PRODUCER_TEAM, c.PRODUCER_EMAIL, c.DESCRIPTION, c.CREATED_AT, c.UPDATED_AT;

-- Contracts with pending breaking changes
CREATE OR REPLACE VIEW GOVERNANCE.CONTRACT_REGISTRY.VW_PENDING_BREAKING_CHANGES AS
SELECT 
    cv.CONTRACT_ID,
    cv.VERSION AS NEW_VERSION,
    cv.PREVIOUS_VERSION,
    cv.CHANGE_DESCRIPTION,
    cv.BREAKING_CHANGES,
    cv.CREATED_AT AS PROPOSED_AT,
    cv.CREATED_BY AS PROPOSED_BY,
    COUNT(CASE WHEN bca.STATUS = 'pending' THEN 1 END) AS PENDING_APPROVALS,
    COUNT(CASE WHEN bca.STATUS = 'acknowledged' THEN 1 END) AS ACKNOWLEDGED,
    COUNT(CASE WHEN bca.STATUS = 'objected' THEN 1 END) AS OBJECTIONS
FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_VERSIONS cv
LEFT JOIN GOVERNANCE.CONTRACT_REGISTRY.BREAKING_CHANGE_APPROVALS bca
    ON cv.CONTRACT_ID = bca.CONTRACT_ID 
    AND cv.VERSION = bca.TO_VERSION
WHERE cv.CHANGE_TYPE = 'major'
  AND cv.STATUS = 'pending'
GROUP BY 
    cv.CONTRACT_ID, cv.VERSION, cv.PREVIOUS_VERSION, 
    cv.CHANGE_DESCRIPTION, cv.BREAKING_CHANGES, cv.CREATED_AT, cv.CREATED_BY;

-- Consumer dependencies view
CREATE OR REPLACE VIEW GOVERNANCE.CONTRACT_REGISTRY.VW_CONSUMER_DEPENDENCIES AS
SELECT 
    c.CONTRACT_ID,
    c.VERSION,
    c.STATUS,
    con.CONSUMER_TEAM,
    con.CONSUMER_EMAIL,
    con.USE_CASE,
    con.ACCESS_LEVEL,
    con.REQUIRED_COLUMNS,
    con.NOTIFY_BREAKING,
    con.ACKNOWLEDGED_VERSION,
    CASE 
        WHEN con.ACKNOWLEDGED_VERSION = c.VERSION THEN 'current'
        WHEN con.ACKNOWLEDGED_VERSION IS NULL THEN 'never_acknowledged'
        ELSE 'behind'
    END AS ACKNOWLEDGMENT_STATUS
FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS c
JOIN GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS con
    ON c.CONTRACT_ID = con.CONTRACT_ID
WHERE c.STATUS = 'active';

