    DEADLINE_AT TIMESTAMP_NTZ
);

COMMENT ON TABLE GOVERNANCE.CONTRACT_REGISTRY.BREAKING_CHANGE_APPROVALS IS 
'Tracking consumer acknowledgments for breaking changes';

