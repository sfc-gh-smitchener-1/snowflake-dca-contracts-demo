-- Contract health dashboard
CREATE OR REPLACE VIEW GOVERNANCE.OBSERVABILITY.VW_CONTRACT_HEALTH AS
SELECT 
    c.CONTRACT_ID,
    c.CONTRACT_TYPE,
    c.VERSION,
    c.PRODUCER_TEAM,
    c.STATUS,
    -- Quality score (% of rules passing in last 24 hours)
    COALESCE(
        (SELECT ROUND(100.0 * SUM(CASE WHEN qrr.PASSED THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0), 1)
         FROM GOVERNANCE.CONTRACT_REGISTRY.QUALITY_RULE_RESULTS qrr
         JOIN GOVERNANCE.CONTRACT_REGISTRY.QUALITY_RULES qr ON qrr.RULE_ID = qr.RULE_ID
         WHERE qr.CONTRACT_ID = c.CONTRACT_ID
           AND qrr.EXECUTION_TIME > DATEADD('hour', -24, CURRENT_TIMESTAMP())),
        NULL
    ) AS QUALITY_SCORE_PCT,
    -- SLA compliance (% of SLAs met in last 24 hours)
    COALESCE(
        (SELECT ROUND(100.0 * SUM(CASE WHEN NOT sm.IS_VIOLATION THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0), 1)
         FROM GOVERNANCE.CONTRACT_REGISTRY.SLA_METRICS sm
         WHERE sm.CONTRACT_ID = c.CONTRACT_ID
           AND sm.MEASURED_AT > DATEADD('hour', -24, CURRENT_TIMESTAMP())),
        NULL
    ) AS SLA_COMPLIANCE_PCT,
    -- Consumer count
    (SELECT COUNT(*) FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_CONSUMERS con 
     WHERE con.CONTRACT_ID = c.CONTRACT_ID) AS CONSUMER_COUNT,
    -- Pending acknowledgments
    (SELECT COUNT(*) FROM GOVERNANCE.CONTRACT_REGISTRY.BREAKING_CHANGE_APPROVALS bca
     WHERE bca.CONTRACT_ID = c.CONTRACT_ID AND bca.STATUS = 'pending') AS PENDING_ACKNOWLEDGMENTS
FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACTS c
WHERE c.STATUS = 'active';

-- Missing tags report
CREATE OR REPLACE VIEW GOVERNANCE.OBSERVABILITY.VW_MISSING_GOVERNANCE_TAGS AS
SELECT 
    cc.CONTRACT_ID,
    cc.VERSION,
    cc.COLUMN_NAME,
    CASE WHEN MAX(CASE WHEN ct.TAG_NAME = 'DATA_CLASSIFICATION' THEN 1 ELSE 0 END) = 0 
         THEN TRUE ELSE FALSE END AS MISSING_DATA_CLASSIFICATION,
    CASE WHEN MAX(CASE WHEN ct.TAG_NAME = 'PII_TYPE' THEN 1 ELSE 0 END) = 0 
         THEN TRUE ELSE FALSE END AS MISSING_PII_TYPE,
    CASE WHEN MAX(CASE WHEN ct.TAG_NAME = 'AI_ALLOWED' THEN 1 ELSE 0 END) = 0 
         THEN TRUE ELSE FALSE END AS MISSING_AI_ALLOWED
FROM GOVERNANCE.CONTRACT_REGISTRY.CONTRACT_COLUMNS cc
LEFT JOIN GOVERNANCE.CONTRACT_REGISTRY.COLUMN_TAGS ct ON cc.COLUMN_ID = ct.COLUMN_ID
WHERE cc.IS_SYSTEM_MANAGED = FALSE
GROUP BY cc.CONTRACT_ID, cc.VERSION, cc.COLUMN_NAME
HAVING MISSING_DATA_CLASSIFICATION OR MISSING_PII_TYPE OR MISSING_AI_ALLOWED;

